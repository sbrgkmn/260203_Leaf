// Independent teaching recipe: one axis, three pairs of lateral shoots,
// no secondary blade recursion and no published-study parameter schedules.
export function ontologyRecipe(fullness=1,segmentation=.65){
 const stage={cycles:3,rotation:62,minExpansionLength:0,minContractionLength:0,
  positions:[.27,.5,.29,.5,.32,.5],
  intensities:[.52,.68,.48,.68,.42,.68],
  stemPosition:1,stemIntensity:.82,firstStemIntensity:.82,
  expansion:{position:1,intensity:1},contraction:{position:1,intensity:1}};
 stage.intensities=stage.intensities.map((v,i)=>i%2?.22+.5*segmentation:v*(.5+.5*fullness));
 const params={name:'Simple branching leaf',seedHalfWidth:0,trajectory:'tip',
  leftRightPosition:.5,leftRightIntensity:.5,roundPosition:.5,bladeContinue:false,
  rounding:true,positiveWeight:1.5,negativeWeight:.65,veins:true,points:false,frontier:false,
  variant:{firstRotationFull:false,vectorMode:'axis',contractionLRIntensity:true,
   connectOrigins:true,veinFollowsRounding:false,veinAtControlPoint:false,
   contractionPositionMin:0,contractionIntensityMin:0},
  stages:[stage,{...structuredClone(stage),cycles:0}]};
 // Compensate for recursive edge shortening inside the E schedule.
 // The silhouette remains generated by the engine, with no outline reshaping.
 for(let tier=1;tier<3;tier++){
  const step=generate(params).steps[tier*2];
  const branch=step.points.find(p=>p.id.startsWith('L')&&p.g===tier*2&&p.polarity>0);
  if(branch){
   const length=Math.hypot(branch.x-branch.origin.x,branch.y-branch.origin.y);
   if(length>1e-8)stage.intensities[tier*2]*=5.2*(.5+.5*fullness)*[1,.85,.65][tier]/length;
  }
 }
 return params;
}
// Four activities after Bockemuhl, printed pp. 22–23 (both supplied PDFs,
// PDF p. 7). Circular placement and reverse mature series are interpretive.
export function activityState(progress,profile='development'){
 const phase=Math.min(3,Math.floor(progress*4)),t=progress*4-phase;
 const params=ontologyRecipe(1,.8),stage=params.stages[0];
 params.trajectory='base';
 stage.rotation=68;
 stage.positions=[.48,.5,.38,.5,.32,.5];
 stage.intensities=[.58,.78,.52,.78,.44,.78];
 let length=1,stalk=0;
 if(phase===0){
  stage.cycles=1;stage.intensities[0]=.065;length=.35+.65*t;
 }else if(phase===1){
  stage.cycles=1+Math.round(t);
  stage.intensities=stage.intensities.map((v,i)=>i%2?.58:v*(.55+.45*t));
  params.positiveWeight=.85;
  params.negativeWeight=.65;
 }else{
  stage.cycles=2;
  stage.intensities=stage.intensities.map((v,i)=>i%2?(phase===2?.55-.85*t:-.3):v);
  params.positiveWeight=phase===2?.85-.15*t:.7;
  params.variant.contractionIntensityMin=null;
  params.negativeWeight=phase===2?.65-.15*t:.5;
  if(phase===3)stalk=4*t;
 }
 if(profile==='mature'){
  // Separate organizations vary the balance of activities, rather than
  // copying a developmental frame at a larger scale.
  stage.rotation+=8*Math.sin(progress*Math.PI*2);
  stage.positions[0]+=.07*Math.cos(progress*Math.PI*2);
  stage.intensities=stage.intensities.map((v,i)=>i%2?v:v*(.85+.22*Math.cos(progress*Math.PI*2)));
  length*=.9+.15*Math.sin(progress*Math.PI*2);
 }
 const result=generate(params);
 // Shooting stops at the first E: one undivided pointed primordium.
 const raw=phase===0?result.steps[0]:result.steps.at(-1);
 // Basal elongation is a separate activity: preserve the formed blade and
 // lift it above its existing attachment, leaving the root at y=0.
 const bladeScale=phase===3?1-.45*t:1;
 const move=p=>({...p,x:p.x*bladeScale,y:p.y*length*bladeScale+(p.y>1e-6?stalk:0)});
 const step={...raw,surfaces:raw.surfaces.map(poly=>poly.map(move)),
  branches:raw.branches.map(b=>({...b,a:move(b.a),b:move(b.b)}))};
 if(phase===3){
  const attachment=raw.points.find(p=>p.id==='L.0:C');
  const top=(attachment?.y??2.2)*bladeScale+stalk;
  step.surfaces.push([{x:-.1,y:0},{x:.1,y:0},{x:.1,y:top},{x:-.1,y:top}]);
 }
 return {params,step,activity:['shooting','segmenting','spreading','stemming'][phase],length,stalk};
}
export function ontologyData(){
 const outer=Array.from({length:12},(_,i)=>{
  const angle=75-i*30,progress=((angle-90+360)%360)/360;
  return {...activityState(progress,'mature'),angle};
 });
 return {outer};
}
