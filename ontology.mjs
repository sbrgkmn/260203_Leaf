  const extent=Math.max(...points.map(p=>Math.abs(p.x)));
  const bottom=Math.min(...points.map(p=>p.y)),top=Math.max(...points.map(p=>p.y));
  const sizeWorld=Math.max(2*extent,top-bottom)*1.12;
  const frame={x:-sizeWorld/2,y:(bottom+top-sizeWorld)/2,size:sizeWorld};
