export const VARIATIONS=[
  ['Buttercup','Open shoots',{spread:8}],
  ['Magnolia','Elliptic blade',{spread:-6,fullness:.1,roundness:.2}],
  ['Buttercup','Longer stalk',{origin:.12}],
  ['Fig','Narrow lobes',{fullness:-.7}],
  ['Fig','Soft margins',{roundness:.7}],
  ['Magnolia','Broader blade',{spread:12,fullness:.4}],
  ['Fern','Compact branching',{spread:-12}],
  ['White oak','Soft, full blade',{fullness:.25,roundness:.5}],
].map(([name,label,offsets])=>{
  const p=varyRecipe(studyParams(PRESETS.find(p=>p.name===name)),offsets);
  for(const key of ['sourceKey','sourceFrames','scriptHash'])delete p[key];
  const labels={spread:'branch spread',origin:'first E position',fullness:'fullness control',roundness:'softer margins',bladeStem:'blade stem C strength (first and later)'};
  const changes=Object.entries(offsets).map(([key,value])=>`${labels[key]??key} ${value>0?'+':''}${value}${key==='spread'?'°':''}`).join('; ');
  return {...p,name:`${name} / ${label}`,parent:name,offsets,reference:'Parametric study',
    source:`Derived from the saved ${name} definition`,
    observation:`${label}. Same E/C engine and inherited development schedules.`,
    recipe:`Changes from ${name}: ${changes}. All other growth settings are retained.`};
});

function addStudy(name,parent,params,description){
  const settings=Object.fromEntries(['trajectory','stages','positiveWeight','negativeWeight','rounding','leftRightPosition','leftRightIntensity',...(params.apices?['apices']:[])].map(k=>[k,structuredClone(params[k])]));
  const p=varyRecipe(studyParams(PRESETS.find(p=>p.name===parent)),{settings});
  for(const key of ['sourceKey','sourceFrames','scriptHash'])delete p[key];
  VARIATIONS.push({...p,name,parent,offsets:{settings},reference:'E/C form study',source:`New settings using the ${parent} rule variant`,observation:description,recipe:description+' Every state is generated by E/C; the margin uses the original rational rounding function.'});
}
