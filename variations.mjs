const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
// Always derive from a fixed anchor: no accumulated slider drift, exact neutral reset.
export function varyRecipe(base,values={}) {
  const p=structuredClone(base),v={...NEUTRAL,...values};
  // Explicit study settings establish a new E/C recipe before ordinary offsets.
  if(v.settings)for(const [key,value] of Object.entries(v.settings))p[key]=structuredClone(value);
  p.stages[0].positions[0]=clamp(p.stages[0].positions[0]+v.origin,0,1);
  p.stages.forEach((s,i)=>{
    s.rotation=clamp(s.rotation+v.spread,0,180);
    s.cycles=clamp(s.cycles+(i?v.blades:v.shoots),0,20);
    s.expansion.intensity*=Math.exp(v.fullness*.22);
    s.contraction.intensity*=Math.exp(-v.fullness*.08);
  });
  if(v.roundness>0){p.rounding=true;p.positiveWeight*=Math.exp(-2*v.roundness);p.negativeWeight*=Math.exp(-2*v.roundness);}
  if(v.bladeStem!==undefined){p.stages[1].firstStemIntensity=v.bladeStem;p.stages[1].stemIntensity=v.bladeStem;}
  return p;
}
