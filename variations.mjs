import {PRESETS} from './presets.mjs?v=studio-1';
export const NEUTRAL={origin:0,spread:0,fullness:0,shoots:0,blades:0,roundness:0};
export const MACRO_FIELDS=[
  ['origin','Stalk / blade origin',-.25,.25,.005,'Shift the first branching origin along the axis.'],
  ['spread','Branch spread',-25,25,.5,'Adjust E rotation in both growth phases.'],
  ['fullness','Blade fullness',-1,1,.02,'Balance expansion and contraction across the saved schedules.'],
  ['shoots','Shoot cycles + / −',-3,3,.5,'Add or remove shoot cycles relative to this form.'],
  ['blades','Blade cycles + / −',-2,2,.5,'Add or remove local blade cycles.'],
  ['roundness','Softer margins',0,1,.02,'Soften positive and negative corners without changing growth.'],
];
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
// Always derive from a fixed anchor: no accumulated slider drift, exact neutral reset.
export function varyRecipe(base,values={}) {
  const p=structuredClone(base),v={...NEUTRAL,...values};
  p.stages[0].positions[0]=clamp(p.stages[0].positions[0]+v.origin,0,1);
  p.stages.forEach((s,i)=>{
    s.rotation=clamp(s.rotation+v.spread,0,180);
    s.cycles=clamp(s.cycles+(i?v.blades:v.shoots),0,20);
    s.expansion.intensity*=Math.exp(v.fullness*.22);
    s.contraction.intensity*=Math.exp(-v.fullness*.08);
  });
  if(v.roundness>0){p.rounding=true;p.positiveWeight*=Math.exp(-2*v.roundness);p.negativeWeight*=Math.exp(-2*v.roundness);}
  return p;
}
