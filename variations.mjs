export const VARIATIONS=definitions.map(([name,parent,changes,description])=>{
  const p=varyRecipe(PRESETS.find(p=>p.name===parent),changes);
  return {...p,name,parent,reference:'Variation study',source:`Derived from ${parent}`,observation:description,
    recipe:'Generated by the same E/C rules. Descriptive form study, not a verified species reconstruction.'};
});
// A deterministic local sweep, so neighboring candidates are comparable and reproducible.
export function neighboringVariations(base) {
  return [-.3,0,.3].flatMap(fullness=>[-8,0,8].map(spread=>({
    ...varyRecipe(base,{fullness,spread}),name:`Spread ${spread>0?'+':''}${spread} / Fullness ${fullness>0?'+':''}${fullness.toFixed(1)}`,
  })));
}
